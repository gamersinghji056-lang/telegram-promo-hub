export function normalizeMiniLanguage(value?: string | null): MiniLanguage {
  return MINI_LANGUAGES.includes(value as MiniLanguage) ? value as MiniLanguage : "en";
}

export function miniT(language: string | null | undefined, text: string) {
  const lang = normalizeMiniLanguage(language);
  return dictionaries[lang][text] ?? text;
}

export function applyMiniAppTranslations(language: string | null | undefined, root: ParentNode = document.body) {
  const lang = normalizeMiniLanguage(language);
  document.documentElement.dir = lang === "fa" ? "rtl" : "ltr";
  document.documentElement.lang = lang;
  if (lang === "en") return;
  const translateNode = (node: Element) => {
    for (const attr of ["placeholder", "aria-label", "title"]) {
      const value = node.getAttribute(attr);
      if (value && dictionaries[lang][value]) node.setAttribute(attr, dictionaries[lang][value]);
    }
  };
  root.querySelectorAll?.("*").forEach(translateNode);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let current = walker.nextNode();
  while (current) {
    const raw = current.textContent ?? "";
    const trimmed = raw.trim();
    if (trimmed && dictionaries[lang][trimmed]) {
      current.textContent = raw.replace(trimmed, dictionaries[lang][trimmed]);
    }
    current = walker.nextNode();
  }
}
